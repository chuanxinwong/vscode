const RCON = new Uint8Array([0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]);

function xtime(a: number): number {
  return ((a << 1) ^ (a & 0x80 ? 0x1b : 0)) & 0xff;
}

function gmul(a: number, b: number): number {
  let p = 0;
  for (let i = 0; i < 8; i++) {
    if (b & 1) { p ^= a; }
    const hi = a & 0x80;
    a = (a << 1) & 0xff;
    if (hi) { a ^= 0x1b; }
    b >>= 1;
  }
  return p;
}

function keyExpansion(key: Uint8Array): Uint8Array {
  const w = new Uint8Array(176);
  w.set(key.subarray(0, 16));
  for (let i = 4; i < 44; i++) {
    const p = i * 4;
    let t0 = w[p - 4], t1 = w[p - 3], t2 = w[p - 2], t3 = w[p - 1];
    if (i % 4 === 0) {
      const tmp = t0;
      t0 = SBOX[t1] ^ RCON[i / 4 - 1];
      t1 = SBOX[t2]; t2 = SBOX[t3]; t3 = SBOX[tmp];
    }
    const base = (i - 4) * 4;
    w[p] = w[base] ^ t0; w[p + 1] = w[base + 1] ^ t1;
    w[p + 2] = w[base + 2] ^ t2; w[p + 3] = w[base + 3] ^ t3;
  }
  return w;
}

function addRoundKey(state: Uint8Array, rk: Uint8Array, round: number): void {
  const base = round * 16;
  for (let i = 0; i < 16; i++) { state[i] ^= rk[base + i]; }
}

function shiftRows(state: Uint8Array): void {
  let t = state[1]; state[1] = state[5]; state[5] = state[9]; state[9] = state[13]; state[13] = t;
  t = state[2]; state[2] = state[10]; state[10] = t; t = state[6]; state[6] = state[14]; state[14] = t;
  t = state[15]; state[15] = state[11]; state[11] = state[7]; state[7] = state[3]; state[3] = t;
}

function invShiftRows(state: Uint8Array): void {
  let t = state[13]; state[13] = state[9]; state[9] = state[5]; state[5] = state[1]; state[1] = t;
  t = state[2]; state[2] = state[10]; state[10] = t; t = state[6]; state[6] = state[14]; state[14] = t;
  t = state[3]; state[3] = state[7]; state[7] = state[11]; state[11] = state[15]; state[15] = t;
}

function mixColumns(state: Uint8Array): void {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a = state[i], b = state[i + 1], cv = state[i + 2], d = state[i + 3];
    const a2 = xtime(a), b2 = xtime(b), c2 = xtime(cv), d2 = xtime(d);
    state[i] = a2 ^ b2 ^ b ^ cv ^ d;
    state[i + 1] = a ^ b2 ^ c2 ^ cv ^ d;
    state[i + 2] = a ^ b ^ c2 ^ d2 ^ d;
    state[i + 3] = a2 ^ a ^ b ^ cv ^ d2;
  }
}

function invMixColumns(state: Uint8Array): void {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a = state[i], b = state[i + 1], cv = state[i + 2], d = state[i + 3];
    state[i] = gmul(14, a) ^ gmul(11, b) ^ gmul(13, cv) ^ gmul(9, d);
    state[i + 1] = gmul(9, a) ^ gmul(14, b) ^ gmul(11, cv) ^ gmul(13, d);
    state[i + 2] = gmul(13, a) ^ gmul(9, b) ^ gmul(14, cv) ^ gmul(11, d);
    state[i + 3] = gmul(11, a) ^ gmul(13, b) ^ gmul(9, cv) ^ gmul(14, d);
  }
}

function encryptBlock(block: Uint8Array, rk: Uint8Array): Uint8Array {
  const state = new Uint8Array(block);
  addRoundKey(state, rk, 0);
  for (let round = 1; round < 10; round++) {
    for (let i = 0; i < 16; i++) { state[i] = SBOX[state[i]]; }
    shiftRows(state);
    mixColumns(state);
    addRoundKey(state, rk, round);
  }
  for (let i = 0; i < 16; i++) { state[i] = SBOX[state[i]]; }
  shiftRows(state);
  addRoundKey(state, rk, 10);
  return state;
}

function decryptBlock(block: Uint8Array, rk: Uint8Array): Uint8Array {
  const state = new Uint8Array(block);
  addRoundKey(state, rk, 10);
  for (let round = 9; round >= 1; round--) {
    invShiftRows(state);
    for (let i = 0; i < 16; i++) { state[i] = ISBOX[state[i]]; }
    addRoundKey(state, rk, round);
    invMixColumns(state);
  }
  invShiftRows(state);
  for (let i = 0; i < 16; i++) { state[i] = ISBOX[state[i]]; }
  addRoundKey(state, rk, 0);
  return state;
}

function utf8Encode(str: string): Uint8Array {
  const bytes: number[] = [];
  for (let i = 0; i < str.length; i++) {
    const c = str.charCodeAt(i);
    if (c < 0x80) {
      bytes.push(c);
    } else if (c < 0x800) {
      bytes.push(0xc0 | (c >> 6), 0x80 | (c & 0x3f));
    } else if (c < 0xd800 || c >= 0xe000) {
      bytes.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f));
    } else {
      i++;
      const cp = 0x10000 + ((c & 0x3ff) << 10 | (str.charCodeAt(i) & 0x3ff));
      bytes.push(0xf0 | (cp >> 18), 0x80 | ((cp >> 12) & 0x3f), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f));
    }
  }
  return new Uint8Array(bytes);
}

function utf8Decode(bytes: Uint8Array): string {
  let str = '';
  for (let i = 0; i < bytes.length;) {
    const b = bytes[i];
    let cp: number;
    if (b < 0x80) { cp = b; i++; }
    else if (b < 0xe0) { cp = (b & 0x1f) << 6 | bytes[i + 1] & 0x3f; i += 2; }
    else if (b < 0xf0) { cp = (b & 0x0f) << 12 | (bytes[i + 1] & 0x3f) << 6 | bytes[i + 2] & 0x3f; i += 3; }
    else { cp = (b & 0x07) << 18 | (bytes[i + 1] & 0x3f) << 12 | (bytes[i + 2] & 0x3f) << 6 | bytes[i + 3] & 0x3f; i += 4; }
    if (cp > 0xffff) {
      cp -= 0x10000;
      str += String.fromCharCode(0xd800 + (cp >> 10), 0xdc00 + (cp & 0x3ff));
    } else {
      str += String.fromCharCode(cp);
    }
  }
  return str;
}

function pkcs7Pad(data: Uint8Array): Uint8Array {
  const pad = 16 - (data.length % 16);
  const result = new Uint8Array(data.length + pad);
  result.set(data);
  result.fill(pad, data.length);
  return result;
}

function pkcs7Unpad(data: Uint8Array): Uint8Array {
  return data.subarray(0, data.length - data[data.length - 1]);
}

export default {
  generatekey(): string {
    return 'a123b234c345d456';
  },
  encrypt(word: string): string {
    const rk = keyExpansion(utf8Encode(this.generatekey()));
    const plain = pkcs7Pad(utf8Encode(word));
    const cipher = new Uint8Array(plain.length);
    for (let i = 0; i < plain.length; i += 16) {
      cipher.set(encryptBlock(plain.subarray(i, i + 16), rk), i);
    }
    return encodeBase64(VSBuffer.wrap(cipher));
  },
  decrypt(word: string): string {
    const rk = keyExpansion(utf8Encode(this.generatekey()));
    const cipher = decodeBase64(word).buffer;
    const plain = new Uint8Array(cipher.length);
    for (let i = 0; i < cipher.length; i += 16) {
      plain.set(decryptBlock(cipher.subarray(i, i + 16), rk), i);
    }
    return utf8Decode(pkcs7Unpad(plain));
  },
};
